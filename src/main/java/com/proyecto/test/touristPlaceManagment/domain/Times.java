package com.proyecto.test.touristPlaceManagment.domain;

public class Times {
    
    private int day;
    private int hours;
    private int mins;
    public int getDay() {
        return day;
    }
    public void setDay(int day) {
        this.day = day;
    }
    public int getHours() {
        return hours;
    }
    public void setHours(int hours) {
        this.hours = hours;
    }
    public int getMins() {
        return mins;
    }
    public void setMins(int mins) {
        this.mins = mins;
    }
}
